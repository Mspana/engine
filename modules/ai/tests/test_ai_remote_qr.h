// Golden matrices are one '0'/'1' character per module, row-major, no quiet
// zone. Returns the flat index of the first module that disagrees, or -1.
// Divide the index by the symbol size for a row and column.
static int _first_difference(const PackedByteArray &p_modules, const char *p_golden, int p_size) {
	for (int i = 0; i < p_size * p_size; i++) {
		const uint8_t expected = (p_golden[i] == '1') ? 1 : 0;
		if (p_modules[i] != expected) {
			return i;
		}
	}
	return -1;
}

static void _check_golden(const char *p_text, int p_expected_size, const char *p_golden) {
	int size = 0;
	PackedByteArray modules;
	REQUIRE(AIRemoteQR::encode(String::utf8(p_text), size, modules));
	REQUIRE(size == p_expected_size);
	REQUIRE(modules.size() == p_expected_size * p_expected_size);
	CHECK(_first_difference(modules, p_golden, p_expected_size) == -1);
}

static String _filler(int p_length) {
	return String("a").repeat(p_length);
}

